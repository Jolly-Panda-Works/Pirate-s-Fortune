const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹';

export function formatNumber(value, locale = appStore.get().settings.locale) {
  const str = String(value);
  return locale === 'fa' ? str.replace(/[0-9]/g, (d) => FA_DIGITS[d]) : str;
}

function lookup(tree, key) {
  return key.split('.').reduce((node, part) => (node == null ? undefined : node[part]), tree);
}

export function translate(locale, key, vars) {
  let value = lookup(UI[locale], key);
  if (value === undefined) value = lookup(localization[locale], key);
  if (value === undefined) value = lookup(UI.en, key) ?? lookup(localization.en, key);
  if (value === undefined) return key;
  if (typeof value !== 'string' || !vars) return value;
  return value.replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] === undefined ? `{${name}}` : typeof vars[name] === 'number' ? formatNumber(vars[name], locale) : vars[name]
  );
}

export function t(key, vars) {
  return translate(appStore.get().settings.locale, key, vars);
}

/** React hook: re-renders on locale change. */
export function useT() {
  const locale = useStore(appStore, (s) => s.settings.locale);
  return (key, vars) => translate(locale, key, vars);
}

export function dirOf(locale) {
  return localization[locale]?.dir ?? 'ltr';
}

export function cardTypeName(type, locale = appStore.get().settings.locale) {
  return translate(locale, `cardTypes.${type}`);
}
